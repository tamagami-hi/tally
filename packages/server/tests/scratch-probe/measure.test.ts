import { serve } from "@hono/node-server";
import type { AddressInfo } from "node:net";
import { test } from "vitest";
import { Endpoints } from "../../src/endpoints.ts";
import { Hub } from "../../src/hub.ts";
import { createServiceApp } from "../../src/service.ts";
import { Repos } from "../../../core/src/repos/repos.ts";
import { addRepo } from "../../../core/src/repos/list.ts";
import { tmpDir } from "../../../core/tests/support/tmp.ts";
import { makeTracked } from "../../../core/tests/support/tracked.ts";
import { LISTENING, newerInit, readUntil } from "../../../mcp/tests/support/newer.ts";

const STREAMS = 50, CALLS = 500, HOLD_MS = 60_000;
const mb = (n: number) => (n / 1048576).toFixed(1);
const mem = () => { const m = process.memoryUsage(); return `rss ${mb(m.rss)} MB, heap ${mb(m.heapUsed)} MB`; };

test("measure", async () => {
  const home = await tmpDir("tally-home-");
  const { root } = await makeTracked();
  await addRepo(home, { root, name: "alpha" });
  const hub = new Hub(new Repos(home), { intervalMs: 1000 });
  const endpoints = new Endpoints();
  const app = createServiceApp({ hub, webDir: home, workspace: home, endpoints });
  const server = serve({ fetch: app.fetch, port: 0, hostname: "127.0.0.1" });
  await new Promise((r) => server.once("listening", r));
  const url = `http://127.0.0.1:${(server.address() as AddressInfo).port}/`;
  const call = () => fetch(new URL("mcp", url), newerInit("tools/call", { name: "decision_list", arguments: {} })).then((r) => r.text());
  for (let i = 0; i < 20; i += 1) await call();
  (globalThis as { gc?: () => void }).gc?.();
  const lines = [`before: ${mem()}`];
  const controllers = Array.from({ length: STREAMS }, () => new AbortController());
  const started = Date.now();
  const opened = await Promise.all(controllers.map(async (c) => { const r = await fetch(new URL("mcp", url), newerInit("subscriptions/listen", LISTENING, c.signal)); await readUntil(r.body, "acknowledged"); return r; }));
  lines.push(`50 streams open (${opened.length}): ${mem()}`);
  const t0 = Date.now();
  for (let batch = 0; batch < CALLS / 10; batch += 1) await Promise.all(Array.from({ length: 10 }, call));
  lines.push(`500 calls beside them in ${Date.now() - t0} ms: ${mem()}`);
  await new Promise((r) => setTimeout(r, Math.max(0, HOLD_MS - (Date.now() - started))));
  lines.push(`held ${Date.now() - started} ms: ${mem()}`);
  controllers.forEach((c) => c.abort());
  await new Promise((r) => setTimeout(r, 1000));
  (globalThis as { gc?: () => void }).gc?.();
  lines.push(`closed, 1 s later: ${mem()}`);
  const s0 = Date.now();
  await endpoints.close();
  await hub.stop();
  await new Promise<void>((r) => server.close(() => r()));
  lines.push(`stop ${Date.now() - s0} ms; gc ${typeof (globalThis as { gc?: unknown }).gc}`);
  console.log(lines.join("\n"));
}, 180_000);
